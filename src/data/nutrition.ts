const weekdayShortRu = ["Вс", "Пн", "Вт", "Ср", "Чт", "Пт", "Сб"] as const;

/** Prefer an explicit weekday short ("Пн") from the client. Never default to new Date(). */
export function getWeekdayMenu(weekdayShort?: string | null): DayMenu {
  if (!weekdayShort) return weeklyMenu[0];
  return weeklyMenu.find((d) => d.short === weekdayShort) ?? weeklyMenu[0];
}

export function weekdayShortFromDate(date: Date): string {
  return weekdayShortRu[date.getDay()];
}

type TodayMenuInput = {
  cyclePhase: string;
  sleepHours: number;
  isSick: boolean;
  weekdayShort?: string | null;
};

export function resolveTodayMenu(input: TodayMenuInput): TodayMenuPlan {
  const weekday = getWeekdayMenu(input.weekdayShort);
  const reasonParts: string[] = [];

  if (input.isSick) {
    const adapted = adaptedDayMenus.sick;
    reasonParts.push("режим болезни");
    return {
      mode: "sick",
      title: adapted.title,
      reason: `Сегодня: ${weekday.day.toLowerCase()} · ${reasonParts.join(", ")}`,
      focus: adapted.focus,
      tips: adapted.tips,
      meals: adapted.meals,
      weekday,
    };
  }

  if (input.sleepHours < 6) {
    const adapted = adaptedDayMenus.lowSleep;
    reasonParts.push(`мало сна (${input.sleepHours} ч)`);
    if (input.cyclePhase === "menstruation") reasonParts.push("менструация");
    else if (input.cyclePhase === "luteal") reasonParts.push("ПМС");
    return {
      mode: "lowSleep",
      title: adapted.title,
      reason: `Сегодня: ${weekday.day.toLowerCase()} · ${reasonParts.join(", ")}`,
      focus: adapted.focus,
      tips: adapted.tips,
      meals: adapted.meals,
      weekday,
    };
  }

  if (input.cyclePhase === "menstruation") {
    const adapted = adaptedDayMenus.menstruation;
    return {
      mode: "menstruation",
      title: adapted.title,
      reason: `Сегодня: ${weekday.day.toLowerCase()} · менструация`,
      focus: adapted.focus,
      tips: adapted.tips,
      meals: adapted.meals,
      weekday,
    };
  }

  if (input.cyclePhase === "luteal") {
    const adapted = adaptedDayMenus.luteal;
    return {
      mode: "luteal",
      title: adapted.title,
      reason: `Сегодня: ${weekday.day.toLowerCase()} · ПМС / лютеиновая`,
      focus: adapted.focus,
      tips: adapted.tips,
      meals: adapted.meals,
      weekday,
    };
  }

  const phaseHint =
    input.cyclePhase === "follicular"
      ? "фолликулярная — обычная ротация"
      : input.cyclePhase === "ovulation"
        ? "овуляция — обычная ротация"
        : "по дню недели";

  return {
    mode: "default",
    title: `Меню: ${weekday.day}`,
    reason: `Сегодня: ${weekday.day.toLowerCase()} · ${phaseHint}`,
    focus: weekday.focus,
    tips: [
      "Граммы уже под твой масштаб порций из профиля.",
      "Если голодно на учёбе — +10–15 г крупы, не ломая день.",
    ],
    meals: weekday.meals,
    weekday,
  };
}

